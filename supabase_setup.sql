-- Run this once in Supabase Dashboard > SQL Editor.
-- Stores each signed-in user's PetCare application data in a row protected by RLS.

create table if not exists public.petcare_data (
    user_id uuid primary key references auth.users (id) on delete cascade,
    data jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.pets (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    name text not null,
    breed text,
    weight numeric,
    animal text,
    created_at timestamptz not null default now(),
    photo_url text
);

create index if not exists pets_user_id_idx on public.pets (user_id);

revoke all privileges on table public.petcare_data, public.pets from anon, authenticated, public;
grant select, insert, update on public.petcare_data to authenticated;
grant select, insert, update, delete on public.pets to authenticated;

alter table public.petcare_data enable row level security;
alter table public.pets enable row level security;

drop policy if exists "Users can read their own PetCare data" on public.petcare_data;
create policy "Users can read their own PetCare data"
    on public.petcare_data for select
    to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own PetCare data" on public.petcare_data;
create policy "Users can insert their own PetCare data"
    on public.petcare_data for insert
    to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own PetCare data" on public.petcare_data;
create policy "Users can update their own PetCare data"
    on public.petcare_data for update
    to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

drop policy if exists "allow select pets" on public.pets;
drop policy if exists "allow inserts pets" on public.pets;
drop policy if exists "Users can view their own pets" on public.pets;
create policy "Users can view their own pets"
    on public.pets for select
    to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own pets" on public.pets;
create policy "Users can add their own pets"
    on public.pets for insert
    to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own pets" on public.pets;
create policy "Users can update their own pets"
    on public.pets for update
    to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own pets" on public.pets;
create policy "Users can delete their own pets"
    on public.pets for delete
    to authenticated
    using ((select auth.uid()) = user_id);

