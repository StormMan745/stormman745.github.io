// Preserve classic-script globals: old pages, inline-free controls and file://
// all use the same API. Concatenation order is part of the application contract.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),zlib=require('node:zlib');
const {transformSync}=require('esbuild');
const root=path.resolve(__dirname,'..');
const check=process.argv.includes('--check');
const scripts=['experience.js','sync.js','script.js','offline-files.js','documents.js','care.js','routine.js','pet-scene.js','extras.js'];
const styles=['style.css','documents.css','experience.css','clinics.css','care.css','polish.css','extras.css'];
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const stats=[];
for(const [extension,files] of [['js',scripts],['css',styles]]){
    const source=files.map(read).join(extension==='js'?'\n;\n':'\n');
    const code=transformSync(source,{loader:extension,target:'es2020',charset:'utf8',minifyWhitespace:true,minifySyntax:true,minifyIdentifiers:false,legalComments:'inline'}).code;
    const result='/* Generated by tools/build-app.cjs. Edit the source files. */\n'+code;
    const name='app.bundle.'+extension;
    if(check){if(read(name)!==result)throw new Error(name+' is stale; run npm run --prefix tools build:app');}
    else fs.writeFileSync(path.join(root,name),result);
    stats.push({name,files:files.length,sourceBytes:Buffer.byteLength(source),bundleBytes:Buffer.byteLength(result),gzipBytes:zlib.gzipSync(result).length,hash:crypto.createHash('sha256').update(result).digest('hex').slice(0,12)});
}
let html=read('index.html');
if(check){
    for(const item of stats)if(!html.includes(item.name+'?v='+item.hash))throw new Error('Stale HTML asset version: '+item.name);
    for(const item of stats)if(!read('sw.js').includes('"/'+item.name+'"'))throw new Error('Missing offline asset: '+item.name);
    console.log('PASS: generated assets and HTML versions match readable sources; bundles are in the offline shell.');
    process.exit(0);
}
const pattern=names=>names.map(name=>name.replaceAll('.','\\.')).join('|');
html=html.replace(new RegExp('    <link rel="stylesheet" href="(?:'+pattern([...styles,'app.bundle.css'])+')(?:\\?[^"<>]*)?">\\r?\\n','g'),'');
html=html.replace('</head>',`    <link rel="stylesheet" href="app.bundle.css?v=${stats[1].hash}">\n</head>`);
html=html.replace(new RegExp('<script src="(?:'+pattern([...scripts,'app.bundle.js'])+')(?:\\?[^"<>]*)?"></script>\\r?\\n','g'),'');
html=html.replace('</body>',`<script src="app.bundle.js?v=${stats[0].hash}"></script>\n</body>`);
fs.writeFileSync(path.join(root,'index.html'),html);
let sw=read('sw.js').replace(/petcare-shell-v\d+-[\w-]+/,'petcare-shell-v53-assistant-chat');
for(const file of [...scripts,...styles])sw=sw.replace(new RegExp('    "/'+file.replaceAll('.','\\.')+'",\\r?\\n'),'');
if(!sw.includes('"/app.bundle.js"'))sw=sw.replace('    "/index.html",','    "/index.html",\n    "/app.bundle.js",\n    "/app.bundle.css",');
fs.writeFileSync(path.join(root,'sw.js'),sw);
console.log(JSON.stringify(stats,null,2));
