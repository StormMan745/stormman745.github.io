const assert = require('node:assert/strict');
function pdf() {
    const stream = 'BT /F1 20 Tf 30 700 Td (Veterinary prescription 12.11.2026) Tj 0 -30 Td (Amoxicillin - verify with veterinarian) Tj ET';
    const objects = ['<< /Type /Catalog /Pages 2 0 R >>', '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
        '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>', `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`];
    let result = '%PDF-1.4\n', offsets = [0];
    objects.forEach((object,i) => { offsets.push(Buffer.byteLength(result)); result += `${i+1} 0 obj\n${object}\nendobj\n`; });
    const start = Buffer.byteLength(result);
    result += `xref\n0 6\n0000000000 65535 f \n` + offsets.slice(1).map(n=>`${String(n).padStart(10,'0')} 00000 n \n`).join('');
    return Buffer.from(result + `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${start}\n%%EOF`);
}
