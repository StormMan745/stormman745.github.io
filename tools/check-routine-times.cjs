const assert = require('node:assert/strict');
module.exports = async ({ page, context, profiles, uid, base, setAvailable }) => {
  const times = ['07:00', '10:00', '13:00', '17:00', '21:00'];
  const edit = () => page.locator('[data-routine="edit"][data-task-id="walk"]').click();
  const fields = () => page.locator('#routineTimesGrid input');
  const values = () => fields().evaluateAll(inputs => inputs.map(input => input.value));
  const displayed = () => page.locator('[data-task="walk"] .routine-check-time').allTextContents();
  const marks = () => page.locator('[data-task="walk"] [data-routine="toggle"]');
  const states = () => marks().evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-pressed') === 'true'));
  const save = async () => { await page.locator('#routineSave').click(); await page.waitForFunction(() => !document.getElementById('routineDialog').open); };
  const saved = () => profiles.get(uid).data.pets.find(pet => pet.id === 'pet-one').dailyRoutine.find(task => task.id === 'walk');
  await edit(); assert.deepEqual(await values(), ['18:00'], 'Old single-time routines remain compatible');
  await page.locator('#routineChecks').fill('5');
  assert.equal(await fields().count(), 5);
  assert.deepEqual(await values(), ['18:00', '', '', '', '']);
  await page.locator('#routineSave').click();
  assert(await page.locator('#routineDialog').evaluate(dialog => dialog.open), 'Every occurrence must have a time');
  for (let i = 0; i < times.length; i++) await fields().nth(i).fill(times[i]);
  await save();
  assert.deepEqual(saved().times, times); assert.equal(saved().time, times[0]);
  assert.deepEqual(await displayed(), times);
  assert.match(await marks().nth(1).getAttribute('aria-label'), /10:00/);
  await marks().nth(1).click(); await page.waitForFunction(() => !document.querySelector('[data-task="walk"] [data-step="2"]').disabled);
  assert.deepEqual(await states(), [false, true, false, false, false]);
  assert.match(await page.evaluate(() => appData.activityHistory.find(row => row.title.includes('Прогулка') && row.title.includes('2 из 5')).note), /10:00/);
  await edit(); await fields().nth(0).fill('06:30'); times[0] = '06:30'; await save();
  assert.deepEqual(await displayed(), times); assert.deepEqual(await states(), [false, true, false, false, false]);
  await edit(); await page.locator('#routineChecks').fill('2'); await save();
  assert.deepEqual(saved().times, times, 'Reducing the count preserves hidden times');
  await edit(); await page.locator('#routineChecks').fill('5'); assert.deepEqual(await values(), times); await save();
  assert.deepEqual(await states(), [false, true, false, false, false]);
  await edit(); await page.locator('#routineChecks').fill('8');
  for (let i = 5; i < 8; i++) await fields().nth(i).fill('22:' + String(i).padStart(2, '0'));
  const draft = await values(); await page.locator('#routineChecks').fill('3'); await page.locator('#routineChecks').fill('8');
  assert.deepEqual(await values(), draft, 'Draft times survive count changes');
  await page.keyboard.press('Escape'); assert.deepEqual(await displayed(), times, 'Cancel does not save the draft');
  setAvailable(false); await context.setOffline(true);
  await edit(); await fields().nth(4).fill('22:30'); times[4] = '22:30'; await save();
  await page.reload(); await page.waitForFunction(() => window.PetCareRoutine && activeUserId && document.querySelectorAll('[data-task="walk"] .routine-check-time').length === 5);
  assert.deepEqual(await displayed(), times, 'Offline reload keeps each time');
  setAvailable(true); await context.setOffline(false); await page.evaluate(() => PetCareSync.flush()); await page.waitForFunction(() => PetCareSync.state.phase === 'saved');
  assert.deepEqual(saved().times, times);
  const second = await context.newPage(); await second.goto(base);
  await second.waitForFunction(() => window.PetCareRoutine && activeUserId && document.querySelectorAll('[data-task="walk"] .routine-check-time').length === 5);
  assert.deepEqual(await second.locator('[data-task="walk"] .routine-check-time').allTextContents(), times, 'Another tab loads the saved schedule'); await second.close();
  await page.evaluate(async () => { appData.pets.push({ id: 'pet-two', name: 'Второй питомец', animal: '🐱' }); await saveData(); switchPet('pet-two'); });
  assert.equal(await marks().count(), 1); assert.match(await page.locator('[data-task="walk"] .task-info').innerText(), /18:00/);
  await page.evaluate(() => switchPet('pet-one')); assert.deepEqual(await displayed(), times);
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 950 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Home fits ' + width);
    assert(await marks().evaluateAll(buttons => buttons.every(button => Math.abs(button.getBoundingClientRect().top - buttons[0].getBoundingClientRect().top) < 1)), 'Marks keep their row');
    await page.locator('[data-task="walk"]').screenshot({ path: `.tools/routine-times-${width}.png` });
    await edit(); assert.deepEqual(await values(), times);
    assert(await page.locator('#routineDialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), 'Editor fits ' + width);
    await page.locator('#routineDialog').screenshot({ path: `.tools/routine-times-editor-${width}.png` }); await page.keyboard.press('Escape');
  }
  console.log('PASS: five individual times, validation, legacy data, completion/history, resizing count, cancellation, offline reload/sync, second tab, pet isolation and 320/390/1440 layouts. Services mocked.');
};
