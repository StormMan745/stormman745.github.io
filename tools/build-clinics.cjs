// Dependency-free classic bundle: usable on HTTPS and directly from local index.html.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const source = read('clinics.js').replace(/^export function /gm, 'function ');
if (/^(?:import|export)\s/m.test(source)) throw new Error('Unbundled module syntax');
const bundle = `/* Generated by tools/build-clinics.cjs. Built-in Yandex directory. */\n(() => {\n'use strict';\n${source}\nwindow.PetCareClinics = Object.freeze({ open });\n})();\n`;
fs.writeFileSync(path.join(root, 'clinics.bundle.js'), bundle);
console.log(`clinics.bundle.js: ${Buffer.byteLength(bundle)} bytes`);
