// Dependency-free classic bundle: usable on HTTPS and directly from local index.html.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const tz = read('assets/vendor/tz-lookup/tz.js').replace(/^export default tzlookup;\s*$/m, '');
const data = read('clinic-data.js').replace(/^export function /gm, 'function ');
const ui = read('clinics.js').replace(/^import [^\n]+\n/gm, '').replace(/^export function /gm, 'function ');
const source = `${tz}\n${data}\n${ui}`;
if (/^(?:import|export)\s/m.test(source)) throw new Error('Unbundled module syntax');
const bundle = `/* Generated by tools/build-clinics.cjs. tz-lookup: CC0-1.0, see assets/vendor/tz-lookup/LICENSE. */\n(() => {\n'use strict';\n${source}\nwindow.PetCareClinics = Object.freeze({ open });\n})();\n`;
fs.writeFileSync(path.join(root, 'clinics.bundle.js'), bundle);
console.log(`clinics.bundle.js: ${Buffer.byteLength(bundle)} bytes`);
