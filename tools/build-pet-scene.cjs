// Rebuild with: npm ci --prefix tools && npm run --prefix tools build:pet-scene
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'pet-scene.js'), 'utf8');
const names = [...new Set([...source.matchAll(/\bT\.(\w+)/g)].map(match => match[1]))].sort();
if (!names.length) throw new Error('No Three.js exports found');
esbuild.buildSync({
    stdin: {
        contents: `export { ${names.join(', ')} } from './assets/vendor/three/three.module.min.js';`,
        resolveDir: root,
        sourcefile: 'petcare-three-entry.js'
    },
    outfile: path.join(root, 'assets/vendor/three/three.runtime.min.js'),
    bundle: true,
    format: 'iife',
    globalName: 'PetCareThree',
    minify: true,
    target: 'es2020',
    legalComments: 'inline',
    banner: { js: '/* PetCare Three.js runtime. Generated by tools/build-pet-scene.cjs. MIT license: ./LICENSE.txt */' }
});
console.log(`Built classic Three.js runtime with ${names.length} exports`);
